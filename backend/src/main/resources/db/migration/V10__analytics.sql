-- First-party, anonymous site analytics: page views, time on page and booking-funnel steps.
-- No names, emails or IPs are stored; the visitor id is a random token held in the visitor's browser.
CREATE TABLE analytics_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visitor_id  VARCHAR(40)  NOT NULL,
    session_id  VARCHAR(40)  NOT NULL,
    kind        VARCHAR(30)  NOT NULL,
    path        VARCHAR(200) NOT NULL,
    referrer    VARCHAR(200),
    device      VARCHAR(10)  NOT NULL,
    duration_ms INTEGER,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_analytics_event_time ON analytics_event (occurred_at);
