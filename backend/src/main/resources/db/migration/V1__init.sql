-- Studio admin accounts (seeded from configuration on boot)
CREATE TABLE admin_user (
    name          VARCHAR(60)  PRIMARY KEY,
    role          VARCHAR(120) NOT NULL,
    password_hash VARCHAR(100) NOT NULL
);

-- Price list: a session type and its packages
CREATE TABLE session_type (
    type_key    VARCHAR(40)  PRIMARY KEY,
    name        VARCHAR(80)  NOT NULL,
    description VARCHAR(300) NOT NULL,
    from_price  VARCHAR(20)  NOT NULL,
    sort_order  INTEGER      NOT NULL DEFAULT 0
);

CREATE TABLE pricing_tier (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_type_key VARCHAR(40)  NOT NULL REFERENCES session_type (type_key) ON DELETE CASCADE,
    name             VARCHAR(80)  NOT NULL,
    detail           VARCHAR(200) NOT NULL DEFAULT '',
    price            VARCHAR(20)  NOT NULL,
    sort_order       INTEGER      NOT NULL DEFAULT 0
);
CREATE INDEX idx_pricing_tier_type ON pricing_tier (session_type_key, sort_order);

-- Session requests from the website → confirmed sessions
CREATE TABLE booking (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_type_key VARCHAR(40)  NOT NULL,
    name             VARCHAR(120) NOT NULL,
    email            VARCHAR(200) NOT NULL,
    phone            VARCHAR(40),
    location         VARCHAR(200),
    notes            TEXT,
    session_date     DATE         NOT NULL,
    session_time     VARCHAR(40)  NOT NULL,
    status           VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    quote            NUMERIC(10, 2),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_booking_status_date ON booking (status, session_date);

-- Pop-up events at markets, with on-site print sales
CREATE TABLE popup_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_date  DATE         NOT NULL,
    title       VARCHAR(120) NOT NULL,
    theme       VARCHAR(120) NOT NULL,
    venue       VARCHAR(160) NOT NULL,
    hours       VARCHAR(60)  NOT NULL,
    prints_sold INTEGER      NOT NULL DEFAULT 0,
    print_price NUMERIC(8, 2) NOT NULL DEFAULT 10
);
CREATE INDEX idx_popup_event_date ON popup_event (event_date);

-- Delivery pipeline for a confirmed session: 0 shot, 1 editing, 2 proofing, 3 delivered
CREATE TABLE gallery (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT  NOT NULL UNIQUE REFERENCES booking (id) ON DELETE CASCADE,
    stage      INTEGER NOT NULL DEFAULT 0
);

-- Website photo slots → S3 objects
CREATE TABLE site_photo (
    slot_id      VARCHAR(60)  PRIMARY KEY,
    s3_key       VARCHAR(300) NOT NULL,
    content_type VARCHAR(80)  NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL
);
