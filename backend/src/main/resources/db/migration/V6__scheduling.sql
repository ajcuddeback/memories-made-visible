-- Real scheduling: bookings occupy a time range, hours are per weekday, and the admin can block time.
ALTER TABLE booking ADD COLUMN start_time TIME;
ALTER TABLE booking ADD COLUMN end_time TIME;
ALTER TABLE session_type ADD COLUMN duration_minutes INTEGER NOT NULL DEFAULT 60;

-- Booking window per weekday (0 = Sunday … 6 = Saturday)
CREATE TABLE availability_hours (
    weekday    INTEGER PRIMARY KEY,
    open       BOOLEAN NOT NULL DEFAULT TRUE,
    start_time TIME    NOT NULL DEFAULT '07:00',
    end_time   TIME    NOT NULL DEFAULT '18:00'
);
INSERT INTO availability_hours (weekday) VALUES (0), (1), (2), (3), (4), (5), (6);

-- Time the studio is unavailable (appointments, holidays…). Times NULL = whole day(s). Never shown publicly.
CREATE TABLE time_block (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    start_date DATE NOT NULL,
    end_date   DATE NOT NULL,
    start_time TIME,
    end_time   TIME,
    note       VARCHAR(200),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_time_block_dates ON time_block (start_date, end_date);

-- One row per day, locked (SELECT … FOR UPDATE) while a booking for that day is checked and written,
-- so two requests for the same slot can't both succeed.
CREATE TABLE calendar_day (
    cal_date DATE PRIMARY KEY
);
